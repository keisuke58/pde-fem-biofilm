"""Hold the implementation against a genuinely independent closed form.

`reference_values.json` is generated by calling the implementation, so
agreement with it establishes nothing. `closed_form_reference.py` derives the
same two cases from the continuum statement of the model and imports nothing
from the code under test, which makes this comparison real.

The comparison currently *fails* in the naive sense -- the implementation does
not reproduce the closed form for constrained growth. That is the known
mis-scaled isochoric split of DEVIATOR_SCALING_FINDING.md, and it is deliberate
that these tests do not paper over it with a loose tolerance. Instead they
assert the discrepancy equals the term that analysis predicts, in closed form,
to near machine precision. So the tests pin two things at once: that the
implementation has not drifted, and that our explanation of *why* it differs is
still correct. If someone fixes the split, `test_constrained_growth_...` fails
loudly and points at this file rather than silently passing.

Requires gfortran; skipped where absent.
"""
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

import numpy as np
import pytest

_ROOT = Path(__file__).resolve().parents[1]
_AU = _ROOT / "ansys_usermat"
_REF = _AU / "apdl" / "closed_form_reference.py"
_FC = shutil.which("gfortran")
_CC = shutil.which("cc") or shutil.which("gcc")

pytestmark = pytest.mark.skipif(
    _FC is None or _CC is None or not _REF.exists(),
    reason="gfortran/cc or the closed-form reference is unavailable")

sys.path.insert(0, str(_AU / "apdl"))
import closed_form_reference as cf  # noqa: E402

# The material of reference_values.json, so the two can be read side by side.
C10, C01, D1, MTYPE, DT = 2.0e-4, 0.0, 5000.0, 0.0, 5.0
I3 = np.eye(3)


@pytest.fixture(scope="module")
def core_exe():
    tmp = Path(tempfile.mkdtemp())
    o = {n: tmp / f"{n}.o" for n in ("hook", "core", "shim")}
    subprocess.run([_FC, "-c", "-ffixed-line-length-132", "-J", str(tmp),
                    str(_AU / "coupling" / "usermat_py_hook.f"),
                    "-o", str(o["hook"])], check=True, cwd=tmp)
    subprocess.run([_FC, "-c", "-ffixed-line-length-132", "-I", str(tmp),
                    str(_AU / "usermat_biofilm.f"), "-o", str(o["core"])],
                   check=True, cwd=tmp)
    subprocess.run([_CC, "-c", "-fPIC",
                    str(_AU / "coupling" / "biofilm_py_eval.c"),
                    "-o", str(o["shim"])], check=True)
    exe = tmp / "core"
    subprocess.run([_FC, "-ffixed-line-length-132", "-I", str(tmp),
                    str(_AU / "crosscheck" / "xcheck_driver_ans.f"),
                    str(o["core"]), str(o["hook"]), str(o["shim"]),
                    "-o", str(exe)], check=True)
    return exe


def _run(exe, F, Fv, alpha, eta):
    text = (" ".join(f"{F[i, j]:.17e}" for i in range(3) for j in range(3)) + "\n" +
            " ".join(f"{Fv[i, j]:.17e}" for i in range(3) for j in range(3)) + "\n" +
            f"{alpha:.17e} {C10:.17e} {C01:.17e} {D1:.17e} {eta:.17e} "
            f"{MTYPE:.1f} {DT:.17e}\n")
    r = subprocess.run([str(exe)], input=text, capture_output=True, text=True,
                       env={"PATH": "/usr/bin:/bin"}, timeout=30)
    assert r.returncode == 0, r.stderr
    v = [float(x) for x in r.stdout.split()]
    return np.array(v[:6]), np.array(v[6:15]).reshape(3, 3)



"""make_abaqus_source.py -- one user-subroutine file for Abaqus (user=...), as Abaqus compiles a single
source, all in fixed form: ecology_native.f as it is, then unified_uel.f90 converted from free to fixed
form (statements from column 7, continuation mark in column 6, comments starting in column 1, at most
132 columns as Abaqus's /extend-source allows).

Why not !DEC$ FREEFORM (first version): Abaqus 2024 compiles with ifort /fpp /extend-source, and the
preprocessor read the free-form part as fixed form and joined its lines (IKMHIWI03, 15 Oct 2026, A-11);
Oliver's notes record a mixed-form file that compiled but broke at run time.

    python make_abaqus_source.py [out]        (default p3/uel/unified_uel_abaqus.for)

Check without Abaqus (gfortran, fixed form, preprocessor on, as Abaqus):
    gfortran -cpp -ffixed-form -ffixed-line-length-132 -c unified_uel_abaqus.for
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]


def free_to_fixed(text):
    """free-form Fortran (no '&' or '!' inside strings, no comment after a continuation '&',
    no line starting with '&') to fixed form with 132 columns"""
    out, cont = [], False
    for raw in text.splitlines():
        line = raw.rstrip()
        s = line.lstrip()
        if not s:
            out.append("")
            continue
        if s.startswith("!"):
            out.append("!" + s[1:])                 # comment from column 1 (column 6 would mean continuation)
            continue
        code = line
        ends = code.endswith("&")
        if ends:
            code = code[:-1].rstrip()
        prefix = "     &" if cont else "      "
        new = prefix + code
        if len(new) > 132:
            new = prefix + code.lstrip()
        if len(new) > 132:
            raise ValueError(f"line too long for fixed form after conversion: {line!r}")
        out.append(new)
        cont = ends
    if cont:
        raise ValueError("file ends with a continuation")
    return "\n".join(out) + "\n"


def write(out):
    fixed = (ROOT / "ansys_usermat/coupling/ecology_native.f").read_text()
    free = (HERE / "unified_uel.f90").read_text()
    head = ("C     unified_uel_abaqus.for -- generated by p3/uel/make_abaqus_source.py; do not edit.\n"
            "C     ecology_native.f, then unified_uel.f90 converted to fixed form (132 columns).\n")
    out.write_text(head + fixed.rstrip("\n") + "\n" + free_to_fixed(free))
    return out


if __name__ == "__main__":
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else HERE / "unified_uel_abaqus.for"
    print("wrote", write(out))

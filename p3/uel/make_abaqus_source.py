"""make_abaqus_source.py -- one user-subroutine file for Abaqus (user=...), as Abaqus compiles a single
source: ecology_native.f (fixed form) followed by unified_uel.f90 (free form), switched with the Intel
Fortran directive !DEC$ FREEFORM. For ifort / ifx, which Abaqus uses on IKMHIWI03 and on the Keio server.

    python make_abaqus_source.py [out]        (default p3/uel/unified_uel_abaqus.for)

gfortran ignores the directive; to check the file there, compile the two sources separately (README.md).
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]


def write(out):
    fixed = (ROOT / "ansys_usermat/coupling/ecology_native.f").read_text()
    free = (HERE / "unified_uel.f90").read_text()
    head = ("C     unified_uel_abaqus.for -- generated by p3/uel/make_abaqus_source.py; do not edit.\n"
            "C     ecology_native.f (fixed form), then unified_uel.f90 (free form) after !DEC$ FREEFORM.\n")
    out.write_text(head + fixed.rstrip("\n") + "\n!DEC$ FREEFORM\n" + free)
    return out


if __name__ == "__main__":
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else HERE / "unified_uel_abaqus.for"
    print("wrote", write(out))

"""make_abaqus_source.py -- living_uel_abaqus.for: ecology_native.f as it is, then living_uel.f90 converted to fixed
form (132 columns), one file as Abaqus compiles a single user source (the converter of p3/uel/make_abaqus_source.py).

    python make_abaqus_source.py [out]
Check without Abaqus: gfortran -cpp -ffixed-form -ffixed-line-length-132 -c living_uel_abaqus.for
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
sys.path.insert(0, str(ROOT / "p3/uel"))
from make_abaqus_source import free_to_fixed  # noqa: E402

out = Path(sys.argv[1]) if len(sys.argv) > 1 else HERE / "living_uel_abaqus.for"
fixed = (ROOT / "ansys_usermat/coupling/ecology_native.f").read_text()
free = (HERE / "living_uel.f90").read_text(encoding="utf-8") + "\n" + (HERE / "mms_src.f90").read_text(encoding="utf-8")
head = ("C     living_uel_abaqus.for -- generated by abaqus_living/make_abaqus_source.py; do not edit.\n"
        "C     ecology_native.f, then living_uel.f90 converted to fixed form (132 columns).\n")
out.write_text(head + fixed.rstrip("\n") + "\n" + free_to_fixed(free))
print("wrote", out)

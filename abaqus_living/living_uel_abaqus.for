            if (sum(sv(1:eco_nact, q)) > 0d0) then
              if (eco_nact == 4) then                 ! share of group A (species 1, 2)
                sh = sum(sv(1:2, q)) / sum(sv(1:eco_nact, q))
              else
                sh = sv(1, q) / sum(sv(1:eco_nact, q))
              end if
            end if

C     living_uel_abaqus.for -- generated by abaqus_living/make_abaqus_source.py; do not edit.
C     ecology_native.f, then living_uel.f90 converted to fixed form (132 columns).
C     ecology_native.f -- the point model (0D Hamilton ODE, Klempt et al.
C     2026; ecology_jax.ecology_substeps) in Fortran, as a drop-in for
C     usermat_py_hook.f: the same module name biofilm_py_bridge and the
C     same hooks biofilm_ecology_hook / biofilm_ecology_hook_c, so the
C     call-site fragments stay unchanged, but no material server, no
C     socket and no C shim (6 Oct 2026: the server call per integration
C     point was ~100x the rest of an Abaqus run).
C
C     Same scheme as jax_hamilton_0d_5species_demo.newton_step: per
C     sub-step 6 Newton iterations on the 12 residuals in
C     g = (phi_1..5, phi_0, psi_1..5, gamma), each preceded and followed
C     by clip_state; the Jacobian is the exact derivative (jax.jacfwd
C     there, written out here); LU with partial pivoting. Differences to
C     the server are round-off (tests/test_ecology_native.py: <= 1e-12).
C     The Hill gate is off (ecology_constants.K_HILL = 0); a case with
C     K_hill > 0 is not supported here.
C
C     Constants: as material_server.py --case (c*, alpha*, eta_i of Klempt
C     et al. 2026 Table 1, n species, theta checked against the deck) or,
C     without a case, ecology_constants.py (c* = 25, alpha* = 0, eta = 1,
C     5 species). Set once, single-threaded: eco_native_init reads the
C     file named by the environment variable BIOFILM_ECO_CASE
C     (abaqus_composition/write_eco_cfg.py; Abaqus calls it in
C     UEXTERNALDB, ANSYS at the first hook call), or eco_native_set sets
C     them directly.

      module biofilm_py_bridge
        use, intrinsic :: iso_c_binding
        implicit none
        integer, save :: eco_nact = 5
        logical, save :: eco_hascase = .false.
        double precision, save :: eco_cstar = 25.0d0
        double precision, save :: eco_alstar = 0.0d0
        double precision, save :: eco_eta(5) = 1.0d0
        double precision, save :: eco_theta(20) = 0.0d0
        double precision, parameter :: eco_kp1 = 1.0d-4
        logical, save :: eco_inited = .false.
C       optional keyword lines of the configuration file (10 Oct 2026,
C       the calibrated five-species runs, research idea 7):
C         phi_init v1 .. v5   the point model's state at its first call
C                             (the calibration's Day-1 state as
C                             write_eco_cfg.py --phi-init-config writes
C                             it); phi_0 = 1 - sum, psi = 0.999, gamma 0
C         newton N TOL        up to N Newton iterations per sub-step,
C                             stopping when |Q|^2 < TOL (the paper
C                             pipeline's newton_step: 12, 1e-20); the
C                             default 6 without a check is the server's
C         theta_tol X         the deck's theta may differ from the
C                             file's by X relative (APDL reads a 16-digit
C                             decimal differently from Fortran in the
C                             last bit); 0 (default): bit for bit
        double precision, save :: eco_phi_init(5) = 0.0d0
        logical, save :: eco_haveinit = .false.
        integer, save :: eco_nwmax = 6
        double precision, save :: eco_nwtol = 0.0d0
        double precision, save :: eco_thtol = 0.0d0
C       damped Newton (15 Oct 2026, the unified-model element p3/uel):
C       the step is shortened so that phi_i, phi_0, psi_i stay inside
C       (0, 1) by 10 %; off by default (the element runs unchanged)
        logical, save :: eco_damp = .false.
      contains

        subroutine eco_native_set(nact, cstar, alstar, eta, theta,
     &                            hascase)
          integer, intent(in) :: nact
          double precision, intent(in) :: cstar, alstar, eta(5)
          double precision, intent(in) :: theta(20)
          logical, intent(in) :: hascase
          eco_inited = .true.
          eco_nact = nact
          eco_cstar = cstar
          eco_alstar = alstar
          eco_eta = eta
          eco_theta = theta
          eco_hascase = hascase
        end subroutine eco_native_set

        subroutine eco_alstar_get(x)
C         the run's alpha* (from the file, else 0), read before a call
C         that changes it for one point (stress feedback test, 14 Oct)
          double precision, intent(out) :: x
          if (.not. eco_inited) call eco_native_init()
          x = eco_alstar
        end subroutine eco_alstar_get

        subroutine eco_alstar_put(x)
C         alpha* for the next calls; serial runs only (-np 1): the
C         value is shared by all threads
          double precision, intent(in) :: x
          if (.not. eco_inited) call eco_native_init()
          eco_alstar = x
        end subroutine eco_alstar_put

        subroutine eco_native_init()
C         file: n_active / c* alpha* / eta(5) / theta(20), free format
          character(len=512) :: path, line
          character(len=32) :: key
          integer :: st, u, nact, nw
          double precision :: cs, als, eta(5), th(20), v(5), x
          eco_inited = .true.
          call get_environment_variable('BIOFILM_ECO_CASE', path,
     &                                  status=st)
          if (st .ne. 0) return
          open(newunit=u, file=trim(path), status='old', iostat=st)
          if (st .ne. 0) return
          read(u, *, iostat=st) nact
          if (st .eq. 0) read(u, *, iostat=st) cs, als
          if (st .eq. 0) read(u, *, iostat=st) eta
          if (st .eq. 0) read(u, *, iostat=st) th
          if (st .eq. 0) call eco_native_set(nact, cs, als, eta, th,
     &                                       .true.)
C         keyword lines, in any order; an unknown keyword is ignored
          do while (st .eq. 0)
            read(u, '(A)', iostat=st) line
            if (st .ne. 0) exit
            if (len_trim(line) .eq. 0) cycle
            read(line, *, iostat=st) key
            if (st .ne. 0) exit
            if (key .eq. 'phi_init') then
              read(line, *, iostat=st) key, v
              if (st .eq. 0) then
                eco_phi_init = v
                eco_haveinit = .true.
              end if
            else if (key .eq. 'newton') then
              read(line, *, iostat=st) key, nw, x
              if (st .eq. 0) then
                eco_nwmax = max(nw, 1)
                eco_nwtol = x
              end if
            else if (key .eq. 'theta_tol') then
              read(line, *, iostat=st) key, x
              if (st .eq. 0) eco_thtol = x
            end if
          end do
          close(u)
        end subroutine eco_native_init

        subroutine biofilm_ecology_init_state(nact, g, have)
C         the point model's state at its first call at a point, from the
C         file's phi_init line: have = .false. when the file has none
C         (the caller then uses its own start), the state as the paper
C         pipeline's make_initial_state builds it (phi_0 = 1 - sum phi,
C         psi = 0.999 for the active species, gamma = 0)
          integer, intent(in) :: nact
          double precision, intent(out) :: g(12)
          logical, intent(out) :: have
          integer :: i
          double precision :: s
          if (.not. eco_inited) call eco_native_init()
          g = 0.0d0
          have = eco_haveinit
          if (.not. have) return
          s = 0.0d0
          do i = 1, 5
            if (i .le. nact) then
              g(i) = eco_phi_init(i)
              g(6+i) = 0.999d0
              s = s + g(i)
            end if
          end do
          g(6) = 1.0d0 - s
        end subroutine biofilm_ecology_init_state

        subroutine eco_clip(g, mask)
          double precision, intent(inout) :: g(12)
          double precision, intent(in) :: mask(5)
          double precision, parameter :: e = 1.0d-10
          integer :: i
          do i = 1, 5
            g(i) = mask(i) * min(max(g(i), e), 1.0d0 - e)
            g(6+i) = mask(i) * min(max(g(6+i), e), 1.0d0 - e)
          end do
          g(6) = min(max(g(6), e), 1.0d0 - e)
          g(12) = min(max(g(12), -1.0d6), 1.0d6)
        end subroutine eco_clip

        subroutine eco_resjac(g, gp, dt, a, b, c, al, eta, mask, q, jac)
C         residual Q(g; g_prev) of the demo's residual() and dQ/dg
          double precision, intent(in) :: g(12), gp(12), dt, a(5,5)
          double precision, intent(in) :: b(5), c, al, eta(5), mask(5)
          double precision, intent(out) :: q(12), jac(12,12)
          double precision :: p(5), s(5), pd(5), sd(5), ia(5), w(5)
          double precision :: x, d, dd, t1, dt1, u1, du1, k
          integer :: i, j
          k = eco_kp1
          q = 0.0d0
          jac = 0.0d0
          do i = 1, 5
            p(i) = g(i)
            s(i) = g(6+i)
            pd(i) = (g(i) - gp(i)) / dt
            sd(i) = (g(6+i) - gp(6+i)) / dt
            w(i) = p(i) * s(i)
          end do
          do i = 1, 5
            ia(i) = 0.0d0
            do j = 1, 5
              ia(i) = ia(i) + a(i,j) * w(j)
            end do
          end do
          do i = 1, 5
            if (mask(i) .gt. 0.5d0) then
              x = p(i)
              d = (x - 1.0d0)**3 * x**3
              t1 = k * (2.0d0 - 4.0d0 * x) / d
              dd = 3.0d0 * (x - 1.0d0)**2 * x**2 * (2.0d0 * x - 1.0d0)
              dt1 = k * (-4.0d0 * d - (2.0d0 - 4.0d0 * x) * dd) / d**2
              q(i) = t1 + (1.0d0 / eta(i)) * (g(12)
     &             + (eta(i) + eta(i) * s(i)**2) * pd(i)
     &             + eta(i) * p(i) * s(i) * sd(i))
     &             - (c / eta(i)) * s(i) * ia(i)
              jac(i,i) = dt1 + (1.0d0 / eta(i)) * ((eta(i)
     &                 + eta(i) * s(i)**2) / dt + eta(i) * s(i) * sd(i))
              jac(i,6+i) = (1.0d0 / eta(i)) * (2.0d0 * eta(i) * s(i)
     &                   * pd(i) + eta(i) * p(i) * sd(i) + eta(i) * p(i)
     &                   * s(i) / dt) - (c / eta(i)) * ia(i)
              jac(i,12) = 1.0d0 / eta(i)
              do j = 1, 5
                jac(i,j) = jac(i,j) - (c / eta(i)) * s(i) * a(i,j)
     &                   * s(j)
                jac(i,6+j) = jac(i,6+j) - (c / eta(i)) * s(i)
     &                     * a(i,j) * p(j)
              end do
            else
              q(i) = p(i)
              jac(i,i) = 1.0d0
            end if
          end do
          x = g(6)
          d = (x - 1.0d0)**3 * x**3
          dd = 3.0d0 * (x - 1.0d0)**2 * x**2 * (2.0d0 * x - 1.0d0)
          q(6) = g(12) + k * (2.0d0 - 4.0d0 * x) / d
     &         + (x - gp(6)) / dt
          jac(6,6) = k * (-4.0d0 * d - (2.0d0 - 4.0d0 * x) * dd) / d**2
     &             + 1.0d0 / dt
          jac(6,12) = 1.0d0
          do i = 1, 5
            if (mask(i) .gt. 0.5d0) then
              x = s(i)
              u1 = (-2.0d0 * k) / ((x - 1.0d0)**2 * x**3)
     &           - (2.0d0 * k) / ((x - 1.0d0)**3 * x**2)
              du1 = -2.0d0 * k * (-2.0d0 / ((x - 1.0d0)**3 * x**3)
     &            - 3.0d0 / ((x - 1.0d0)**2 * x**4))
     &            - 2.0d0 * k * (-3.0d0 / ((x - 1.0d0)**4 * x**2)
     &            - 2.0d0 / ((x - 1.0d0)**3 * x**3))
              q(6+i) = u1 + (b(i) * al / eta(i)) * s(i)
     &               + p(i) * s(i) * pd(i) + p(i)**2 * sd(i)
     &               - (c / eta(i)) * p(i) * ia(i)
              jac(6+i,6+i) = du1 + b(i) * al / eta(i) + p(i) * pd(i)
     &                     + p(i)**2 / dt
              jac(6+i,i) = s(i) * pd(i) + p(i) * s(i) / dt
     &                   + 2.0d0 * p(i) * sd(i) - (c / eta(i)) * ia(i)
              do j = 1, 5
                jac(6+i,j) = jac(6+i,j) - (c / eta(i)) * p(i)
     &                     * a(i,j) * s(j)
                jac(6+i,6+j) = jac(6+i,6+j) - (c / eta(i)) * p(i)
     &                       * a(i,j) * p(j)
              end do
            else
              q(6+i) = s(i)
              jac(6+i,6+i) = 1.0d0
            end if
          end do
          q(12) = p(1) + p(2) + p(3) + p(4) + p(5) + g(6) - 1.0d0
          do j = 1, 6
            jac(12,j) = 1.0d0
          end do
        end subroutine eco_resjac

        subroutine eco_solve(a, r, x, ok)
C         x = a^{-1} r, Gaussian elimination with partial pivoting
          double precision, intent(inout) :: a(12,12), r(12)
          double precision, intent(out) :: x(12)
          logical, intent(out) :: ok
          double precision :: f, t
          integer :: i, j, kk, piv
          ok = .true.
          do kk = 1, 12
            piv = kk
            do i = kk + 1, 12
              if (abs(a(i,kk)) .gt. abs(a(piv,kk))) piv = i
            end do
            if (a(piv,kk) .eq. 0.0d0) then
              ok = .false.
              return
            end if
            if (piv .ne. kk) then
              do j = 1, 12
                t = a(kk,j)
                a(kk,j) = a(piv,j)
                a(piv,j) = t
              end do
              t = r(kk)
              r(kk) = r(piv)
              r(piv) = t
            end if
            do i = kk + 1, 12
              f = a(i,kk) / a(kk,kk)
              a(i,kk) = 0.0d0
              do j = kk + 1, 12
                a(i,j) = a(i,j) - f * a(kk,j)
              end do
              r(i) = r(i) - f * r(kk)
            end do
          end do
          do i = 12, 1, -1
            t = r(i)
            do j = i + 1, 12
              t = t - a(i,j) * x(j)
            end do
            x(i) = t / a(i,i)
          end do
        end subroutine eco_solve

        subroutine eco_substeps(g, theta, dt_h, n_sub, crel, g_new,
     &                          phi_int, ok)
C         ecology_jax.ecology_substeps: n_sub equal steps over dt_h;
C         phi_int = sum_k dt_sub sum_i phi_i psi_i (state after step k).
C         crel < 0: no local nutrient (c = c*).
          double precision, intent(in) :: g(12), theta(20), dt_h, crel
          integer, intent(in) :: n_sub
          double precision, intent(out) :: g_new(12), phi_int
          logical, intent(out) :: ok
          call eco_substeps_x(g, theta, dt_h, n_sub, crel, .false.,
     &                        0.0d0, 0.0d0, 0.0d0, 0.0d0, g_new,
     &                        phi_int, ok)
        end subroutine eco_substeps

        subroutine biofilm_ecology_hook_lin(g, theta, dt, n_sub, c0, c1,
     &                                      a0, a1, g_new, phi_int, ok)
C         the coupling agreed with the partner on 20 Oct 2026
C         (MEETING_2026-10-20.md, coupled_living_consumption.py): c* and
C         alpha* from the 3D fields, linearly interpolated in time over
C         the inner steps, at the end of inner step k (w = k / n_sub)
C           c*_k = c*_file ((1 - w) c0 + w c1)
C           alpha*_k = alpha*_file ((1 - w) a0 + w a1)
C         c*_file, alpha*_file from the configuration file (Fritsch et
C         al. 2025 Case I: 100 and 10), c, a the fields' values (c = 1 on
C         the nutrient wall). The equations of the point model unchanged.
          real(c_double), intent(in)  :: g(12), theta(20), dt
          real(c_double), intent(in)  :: c0, c1, a0, a1
          integer, intent(in)         :: n_sub
          real(c_double), intent(out) :: g_new(12)
          real(c_double), intent(out) :: phi_int
          logical, intent(out)        :: ok
          call eco_substeps_x(g, theta, dt, n_sub, -1.0d0, .true.,
     &                        c0, c1, a0, a1, g_new, phi_int, ok)
        end subroutine biofilm_ecology_hook_lin

        subroutine eco_substeps_x(g, theta, dt_h, n_sub, crel, lin,
     &                            c0, c1, a0, a1, g_new, phi_int, ok)
C         the body of eco_substeps; lin = .true.: c and alpha per inner
C         step from (c0, c1), (a0, a1) as in biofilm_ecology_hook_lin
          double precision, intent(in) :: g(12), theta(20), dt_h, crel
          double precision, intent(in) :: c0, c1, a0, a1
          logical, intent(in) :: lin
          integer, intent(in) :: n_sub
          double precision, intent(out) :: g_new(12), phi_int
          logical, intent(out) :: ok
          double precision :: a(5,5), b(5), mask(5), gp(12), gg(12)
          double precision :: q(12), jac(12,12), dl(12), dts, c, s
          double precision :: al, w
          integer :: i, it, ks, n
          ok = .false.
          g_new = g
          phi_int = 0.0d0
C         ANSYS has no UEXTERNALDB: read the constants at the first call
C         (single-threaded with -np 1, as the wired decks run)
          if (.not. eco_inited) call eco_native_init()
          if (n_sub .lt. 1) return
          if (eco_hascase) then
            do i = 1, 20
              if (eco_thtol .gt. 0.0d0) then
                if (abs(theta(i) - eco_theta(i)) .gt. eco_thtol
     &              * max(1.0d0, abs(eco_theta(i)))) return
              else
                if (theta(i) .ne. eco_theta(i)) return
              end if
            end do
          end if
          a = 0.0d0
          b = 0.0d0
          a(1,1) = theta(1)
          a(1,2) = theta(2)
          a(2,1) = theta(2)
          a(2,2) = theta(3)
          b(1) = theta(4)
          b(2) = theta(5)
          a(3,3) = theta(6)
          a(3,4) = theta(7)
          a(4,3) = theta(7)
          a(4,4) = theta(8)
          b(3) = theta(9)
          b(4) = theta(10)
          a(1,3) = theta(11)
          a(3,1) = theta(11)
          a(1,4) = theta(12)
          a(4,1) = theta(12)
          a(2,3) = theta(13)
          a(3,2) = theta(13)
          a(2,4) = theta(14)
          a(4,2) = theta(14)
          a(5,5) = theta(15)
          b(5) = theta(16)
          a(1,5) = theta(17)
          a(5,1) = theta(17)
          a(2,5) = theta(18)
          a(5,2) = theta(18)
          a(3,5) = theta(19)
          a(5,3) = theta(19)
          a(4,5) = theta(20)
          a(5,4) = theta(20)
          n = eco_nact
          mask = 0.0d0
          do i = 1, n
            mask(i) = 1.0d0
          end do
          c = eco_cstar
          if (crel .ge. 0.0d0) c = eco_cstar * crel
          gp = g
C         seed_inactive: zero the switched-off species once
          if (n .lt. 5) then
            s = 0.0d0
            do i = n + 1, 5
              s = s + abs(gp(i)) + abs(gp(6+i))
            end do
            if (s .ne. 0.0d0) then
              do i = n + 1, 5
                gp(i) = 0.0d0
                gp(6+i) = 0.0d0
              end do
              s = 0.0d0
              do i = 1, n
                s = s + gp(i)
              end do
              gp(6) = 1.0d0 - s
            end if
          end if
          dts = dt_h / dble(n_sub)
          al = eco_alstar
          do ks = 1, n_sub
            if (lin) then
              w = dble(ks) / dble(n_sub)
              c = eco_cstar * ((1.0d0 - w) * c0 + w * c1)
              al = eco_alstar * ((1.0d0 - w) * a0 + w * a1)
            end if
            gg = gp
            call eco_clip(gg, mask)
            do it = 1, eco_nwmax
              call eco_clip(gg, mask)
              call eco_resjac(gg, gp, dts, a, b, c, al, eco_eta,
     &                        mask, q, jac)
C             the paper pipeline's newton_step keeps g once |Q|^2 < tol
              if (eco_nwtol .gt. 0.0d0) then
                if (sum(q * q) .lt. eco_nwtol) exit
              end if
              q = -q
              call eco_solve(jac, q, dl, ok)
              if (.not. ok) return
              if (eco_damp) then
                s = 1.0d0
                do i = 1, 11
                  if (dl(i) .lt. 0.0d0) then
                    s = min(s, -0.9d0 * gg(i) / dl(i))
                  else if (dl(i) .gt. 0.0d0) then
                    s = min(s, 0.9d0 * (1.0d0 - gg(i)) / dl(i))
                  end if
                end do
                gg = gg + s * dl
              else
                gg = gg + dl
              end if
              call eco_clip(gg, mask)
            end do
            gp = gg
            s = 0.0d0
            do i = 1, 5
              s = s + gg(i) * gg(6+i)
            end do
            phi_int = phi_int + dts * s
          end do
          g_new = gp
          ok = .true.
        end subroutine eco_substeps_x


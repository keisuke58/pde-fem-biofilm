"""mms.py -- manufactured solution for the phi-c part of the agreed coupling (A-50), to verify the Python finite-volume
code and the Abaqus element against a known solution:

    d phi/dt = beta lap phi - v(c) . grad phi + S_phi,  v = r c/(K + c) grad c / sqrt(|grad c|^2 + eps)
    0        = lap c - q phi c + S_c                     (L = 1, quasi-static)

on [-1, 1]^3 mm with zero flux for phi on every face, c = 1 on y = -1 and zero flux for c on the other faces. The point
model, the antibiotic and the k_alpha alpha term are off. Chosen solution (smooth, inside (0, 1), satisfies the BC):

    phi_m = 0.5 + 0.2 (1 + t) cos(pi (x+1)) cos(pi (y+1)) cos(pi (z+1)) / 2
    c_m   = 1 - 0.3 (1 + 0.5 t) sin^2(pi (y+1) / 4) (1 + 0.5 cos(pi (x+1)) cos(pi (z+1)))

S_phi and S_c follow by automatic differentiation (JAX, used by the Python solver) and as sympy expressions (written to
mms_src.f90 for the Abaqus element); `python mms.py` writes the Fortran and checks that both agree.
"""
import math
from pathlib import Path

import numpy as np

EPS = 1e-6          # as front_central (Python) and EPSG (Abaqus element)
PI = math.pi


def phi_m(x, y, z, t, cos=np.cos):
    return 0.5 + 0.1 * (1.0 + t) * cos(PI * (x + 1)) * cos(PI * (y + 1)) * cos(PI * (z + 1))


def c_m(x, y, z, t, cos=np.cos, sin=np.sin):
    return 1.0 - 0.3 * (1.0 + 0.5 * t) * sin(PI * (y + 1) / 4) ** 2 * (1.0 + 0.5 * cos(PI * (x + 1)) * cos(PI * (z + 1)))


def sources_jax(beta, r, K, q):
    """S_phi(x, y, z, t), S_c(x, y, z, t) as jitted, vectorised JAX functions"""
    import jax
    import jax.numpy as jnp
    jax.config.update("jax_enable_x64", True)
    ph = lambda p, t: phi_m(p[0], p[1], p[2], t, cos=jnp.cos)  # noqa: E731
    cc = lambda p, t: c_m(p[0], p[1], p[2], t, cos=jnp.cos, sin=jnp.sin)  # noqa: E731

    def s_phi(p, t):
        dphidt = jax.grad(ph, 1)(p, t)
        g = jax.grad(ph, 0)(p, t)
        lap = jnp.trace(jax.hessian(ph, 0)(p, t))
        gc = jax.grad(cc, 0)(p, t)
        c = cc(p, t)
        v = r * c / (K + c) * gc / jnp.sqrt(jnp.sum(gc ** 2) + EPS)
        return dphidt - beta * lap + jnp.dot(v, g)

    def s_c(p, t):
        lap = jnp.trace(jax.hessian(cc, 0)(p, t))
        return -lap + q * ph(p, t) * cc(p, t)

    vs = jax.jit(jax.vmap(s_phi, (0, None)))
    vc = jax.jit(jax.vmap(s_c, (0, None)))
    return (lambda X, Y, Z, t: np.asarray(vs(jnp.stack([X.ravel(), Y.ravel(), Z.ravel()], 1), t)).reshape(X.shape),
            lambda X, Y, Z, t: np.asarray(vc(jnp.stack([X.ravel(), Y.ravel(), Z.ravel()], 1), t)).reshape(X.shape))


def sources_sympy():
    import sympy as sm
    x, y, z, t, beta, r, K, q = sm.symbols("x y z t beta r K q", real=True)
    ph = phi_m(x, y, z, t, cos=sm.cos)
    c = c_m(x, y, z, t, cos=sm.cos, sin=sm.sin)
    X = (x, y, z)
    g = [sm.diff(ph, s) for s in X]
    gc = [sm.diff(c, s) for s in X]
    nrm = sm.sqrt(sum(v ** 2 for v in gc) + EPS)
    s_phi = sm.diff(ph, t) - beta * sum(sm.diff(ph, s, 2) for s in X) + r * c / (K + c) / nrm * sum(a * b for a, b in zip(gc, g))
    s_c = -sum(sm.diff(c, s, 2) for s in X) + q * ph * c
    return (x, y, z, t, beta, r, K, q), s_phi, s_c, ph, c


def write_fortran(path):
    import sympy as sm
    syms, s_phi, s_c, ph, c = sources_sympy()
    lines = ["! mms_src.f90 -- generated by abaqus_living/mms.py; do not edit (A-50, manufactured solution)",
             "subroutine mms_eval(x, y, z, t, beta, r, K, q, sphi, sc, phim, cm)",
             "  implicit none",
             "  double precision, intent(in) :: x, y, z, t, beta, r, K, q",
             "  double precision, intent(out) :: sphi, sc, phim, cm"]
    for name, e in (("sphi", s_phi), ("sc", s_c), ("phim", ph), ("cm", c)):
        code = sm.fcode(sm.N(e), standard=95, source_format="free", assign_to=name)
        lines.append("  " + code.replace("\n", "\n  "))
    lines.append("end subroutine mms_eval")
    Path(path).write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    import sympy as sm
    here = Path(__file__).resolve().parent
    write_fortran(here / "mms_src.f90")
    syms, s_phi, s_c, _, _ = sources_sympy()
    fp = sm.lambdify(syms, s_phi, "numpy"); fc = sm.lambdify(syms, s_c, "numpy")
    rng = np.random.default_rng(1)
    P = rng.uniform(-1, 1, (200, 3)); t = 0.07
    par = (0.3325, 10.0, 1.0, 1.0)
    jp, jc = sources_jax(*par)
    a1 = jp(P[:, 0], P[:, 1], P[:, 2], t); b1 = fp(P[:, 0], P[:, 1], P[:, 2], t, *par)
    a2 = jc(P[:, 0], P[:, 1], P[:, 2], t); b2 = fc(P[:, 0], P[:, 1], P[:, 2], t, *par)
    print(f"S_phi: JAX vs sympy max |diff| {np.abs(a1 - b1).max():.2e} (max |S| {np.abs(a1).max():.2f}); "
          f"S_c: {np.abs(a2 - b2).max():.2e} (max {np.abs(a2).max():.2f})")
    print("wrote", here / "mms_src.f90")
